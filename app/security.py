"""Service-to-service authentication, authorization and rate limiting.

Layer 1 (transport): Caddy requires a client certificate signed by the private
client CA (mTLS). Layer 2 (application, this module): every non-health endpoint
requires ``Authorization: Bearer <key_id>.<secret>``.

The credentials file (mounted secret) stores only SHA-256 digests of the
secrets. Secrets are 256-bit random values generated by scripts/manage_keys.py,
so an unsalted fast hash is appropriate (no dictionary attack surface).
Each client is bound to an explicit tenant allowlist and scope set; tenant
authorization is derived exclusively from the credential, never from the
request body.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import re
import threading
import time
from dataclasses import dataclass
from pathlib import Path

from fastapi import Depends, Request

from .errors import ServiceError
from .logging_config import client_id_var

SCOPES = frozenset({"evaluate", "rules:read", "rules:write", "rules:admin", "metrics:read", "catalog:read",
                    "catalog:operate", "catalog:review", "catalog:publish", "catalog:automate"})
KEY_ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{2,63}$")
TENANT_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,62}$")
_DUMMY_DIGEST = hashlib.sha256(b"opm-dummy-secret").hexdigest()


@dataclass(frozen=True)
class Principal:
    key_id: str
    tenants: frozenset[str]
    scopes: frozenset[str]

    def can_access_tenant(self, tenant_id: str) -> bool:
        return tenant_id in self.tenants


@dataclass(frozen=True)
class _ClientRecord:
    principal: Principal
    secret_sha256: str
    enabled: bool


class ApiKeyStore:
    def __init__(self, clients: dict[str, _ClientRecord]) -> None:
        self._clients = clients

    @classmethod
    def from_file(cls, path: Path) -> "ApiKeyStore":
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError as exc:
            raise RuntimeError(f"API clients file not found: {path}") from exc
        clients: dict[str, _ClientRecord] = {}
        for entry in raw.get("clients", []):
            key_id = entry["key_id"]
            if not KEY_ID_RE.match(key_id):
                raise RuntimeError(f"invalid key_id in clients file: {key_id!r}")
            digest = entry["secret_sha256"].lower()
            if not re.fullmatch(r"[0-9a-f]{64}", digest):
                raise RuntimeError(f"invalid secret_sha256 for {key_id}")
            scopes = frozenset(entry.get("scopes", []))
            unknown = scopes - SCOPES
            if unknown:
                raise RuntimeError(f"unknown scopes for {key_id}: {sorted(unknown)}")
            tenants = frozenset(entry.get("tenants", []))
            for t in tenants:
                if not TENANT_RE.match(t):
                    raise RuntimeError(f"invalid tenant id for {key_id}: {t!r}")
            if key_id in clients:
                raise RuntimeError(f"duplicate key_id: {key_id}")
            clients[key_id] = _ClientRecord(
                Principal(key_id, tenants, scopes), digest, bool(entry.get("enabled", True))
            )
        if not clients:
            raise RuntimeError("API clients file defines no clients")
        return cls(clients)

    def authenticate(self, token: str) -> Principal | None:
        key_id, sep, secret = token.partition(".")
        record = self._clients.get(key_id) if sep and KEY_ID_RE.match(key_id) else None
        expected = record.secret_sha256 if record else _DUMMY_DIGEST
        presented = hashlib.sha256(secret.encode("utf-8")).hexdigest()
        ok = hmac.compare_digest(presented, expected)  # constant time, always executed
        if record is None or not record.enabled or not ok:
            return None
        return record.principal


class TokenBucketLimiter:
    """In-process token bucket keyed by an identifier (bounded key count)."""

    def __init__(self, rate_per_minute: int, burst: int, max_keys: int = 10_000) -> None:
        self.rate = rate_per_minute / 60.0
        self.burst = float(burst)
        self.max_keys = max_keys
        self._buckets: dict[str, tuple[float, float]] = {}
        self._lock = threading.Lock()

    def allow(self, key: str, cost: float = 1.0) -> tuple[bool, float]:
        now = time.monotonic()
        with self._lock:
            tokens, last = self._buckets.get(key, (self.burst, now))
            tokens = min(self.burst, tokens + (now - last) * self.rate)
            allowed = tokens >= cost
            if allowed:
                tokens -= cost
            self._buckets.pop(key, None)
            self._buckets[key] = (tokens, now)  # re-insert => dict order is LRU
            if len(self._buckets) > self.max_keys:  # bound memory
                self._buckets.pop(next(iter(self._buckets)))
            return (True, 0.0) if allowed else (False, (cost - tokens) / self.rate)


def _client_address(request: Request) -> str:
    settings = request.app.state.settings
    if settings.trust_proxy_headers:
        fwd = request.headers.get("x-forwarded-for")
        if fwd:
            return fwd.split(",")[0].strip()[:64]
    return request.client.host if request.client else "unknown"


async def authenticate(request: Request) -> Principal:
    state = request.app.state
    header = request.headers.get("authorization", "")
    scheme, _, token = header.partition(" ")
    if scheme.lower() != "bearer" or not token or len(token) > 256:
        _record_auth_failure(request)
        raise ServiceError(
            401, "UNAUTHENTICATED", "Missing or malformed credentials.",
            headers={"WWW-Authenticate": "Bearer"},
        )
    principal = state.api_keys.authenticate(token.strip())
    if principal is None:
        _record_auth_failure(request)
        raise ServiceError(
            401, "UNAUTHENTICATED", "Invalid credentials.",
            headers={"WWW-Authenticate": "Bearer"},
        )
    allowed, retry = state.rate_limiter.allow(principal.key_id)
    if not allowed:
        raise ServiceError(
            429, "RATE_LIMITED", "Rate limit exceeded.",
            headers={"Retry-After": str(max(1, int(retry + 0.999)))},
        )
    client_id_var.set(principal.key_id)
    return principal


def _record_auth_failure(request: Request) -> None:
    allowed, retry = request.app.state.auth_failure_limiter.allow(_client_address(request))
    request.app.state.metrics.inc("auth_failures_total")
    if not allowed:
        raise ServiceError(
            429, "RATE_LIMITED", "Too many failed authentication attempts.",
            headers={"Retry-After": str(max(1, int(retry + 0.999)))},
        )


def require_scope(scope: str):
    if scope not in SCOPES:
        raise ValueError(scope)

    async def dependency(principal: Principal = Depends(authenticate)) -> Principal:
        if scope not in principal.scopes:
            raise ServiceError(403, "FORBIDDEN", f"Credential lacks required scope '{scope}'.")
        return principal

    return dependency


def authorize_tenant(principal: Principal, tenant_id: str) -> None:
    if not principal.can_access_tenant(tenant_id):
        # Same message whether or not the tenant exists: no tenant enumeration.
        raise ServiceError(403, "TENANT_FORBIDDEN", "Credential is not authorized for this tenant.")
