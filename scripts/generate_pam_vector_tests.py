"""Interpret PAM vector.db and emit deterministic OPM evidence tests."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from regintel.pam_vector_db import (
    PamVectorDatabase,
    generate_test_vectors,
    validate_test_vectors,
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", required=True, help="PAM vector.db generated by getpamcapablities")
    parser.add_argument("--output", help="Output JSON file; stdout when omitted")
    parser.add_argument("--validate", action="store_true", help="Run every generated schema test before writing")
    args = parser.parse_args()

    with PamVectorDatabase(args.db) as database:
        result = generate_test_vectors(database)
    if args.validate:
        validation = validate_test_vectors(result)
        result["validation"] = validation
        if validation["failed"]:
            print(json.dumps(validation, indent=2, sort_keys=True), file=sys.stderr)
            return 1
    rendered = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        output = Path(args.output).resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary = output.with_name(output.name + ".tmp")
        temporary.write_text(rendered, encoding="utf-8")
        temporary.replace(output)
        print(json.dumps({"output": str(output), **result["summary"]}, sort_keys=True))
    else:
        sys.stdout.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
